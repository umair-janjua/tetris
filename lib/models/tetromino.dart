/// The 7 classic Tetromino piece types.
///
/// The [colorIndex] maps each type to its slot in [AppColors.tetrominoes] (1-7).
enum TetrominoType {
  I, O, T, S, Z, J, L;

  /// 1-based index into the tetrominoes color palette (0 is reserved for empty).
  int get colorIndex => index + 1;
}

// ═══════════════════════════════════════════════════════════════════════════════
// TETROMINO SHAPES  (Standard Rotation System)
// ═══════════════════════════════════════════════════════════════════════════════

/// Shape data for all 7 tetrominos across 4 rotations.
///
/// Each piece is defined in a 4×4 bounding box.
/// Each rotation is a list of [row, col] cell offsets.
/// Rotation order: 0° → 90° CW → 180° → 270° CW.
class TetrominoData {
  TetrominoData._();

  static const Map<TetrominoType, List<List<List<int>>>> shapes = {

    // ── I ────────────────────────────────────────────────────────────────────
    //  Rotation 0:  . . . .     Rotation 1:  . . X .
    //               X X X X                  . . X .
    //               . . . .                  . . X .
    //               . . . .                  . . X .
    TetrominoType.I: [
      [[1, 0], [1, 1], [1, 2], [1, 3]], // 0°
      [[0, 2], [1, 2], [2, 2], [3, 2]], // 90°
      [[2, 0], [2, 1], [2, 2], [2, 3]], // 180°
      [[0, 1], [1, 1], [2, 1], [3, 1]], // 270°
    ],

    // ── O ────────────────────────────────────────────────────────────────────
    //  All rotations identical:  . X X .
    //                            . X X .
    TetrominoType.O: [
      [[0, 1], [0, 2], [1, 1], [1, 2]],
      [[0, 1], [0, 2], [1, 1], [1, 2]],
      [[0, 1], [0, 2], [1, 1], [1, 2]],
      [[0, 1], [0, 2], [1, 1], [1, 2]],
    ],

    // ── T ────────────────────────────────────────────────────────────────────
    //  Rotation 0:  . X .    Rotation 1:  . X .    Rotation 2:  . . .    Rotation 3:  . X .
    //               X X X                . X X                  X X X                X X .
    //               . . .                . X .                  . X .                . X .
    TetrominoType.T: [
      [[0, 1], [1, 0], [1, 1], [1, 2]], // 0°  – stem up
      [[0, 1], [1, 1], [1, 2], [2, 1]], // 90° – stem right
      [[1, 0], [1, 1], [1, 2], [2, 1]], // 180° – stem down
      [[0, 1], [1, 0], [1, 1], [2, 1]], // 270° – stem left
    ],

    // ── S ────────────────────────────────────────────────────────────────────
    //  Rotation 0:  . X X    Rotation 1:  X .
    //               X X .                X X
    //               . . .                . X
    TetrominoType.S: [
      [[0, 1], [0, 2], [1, 0], [1, 1]], // 0°
      [[0, 0], [1, 0], [1, 1], [2, 1]], // 90°
      [[0, 1], [0, 2], [1, 0], [1, 1]], // 180° (same as 0°)
      [[0, 0], [1, 0], [1, 1], [2, 1]], // 270° (same as 90°)
    ],

    // ── Z ────────────────────────────────────────────────────────────────────
    //  Rotation 0:  X X .    Rotation 1:  . X
    //               . X X                X X
    //               . . .                X .
    TetrominoType.Z: [
      [[0, 0], [0, 1], [1, 1], [1, 2]], // 0°
      [[0, 1], [1, 0], [1, 1], [2, 0]], // 90°
      [[0, 0], [0, 1], [1, 1], [1, 2]], // 180° (same as 0°)
      [[0, 1], [1, 0], [1, 1], [2, 0]], // 270° (same as 90°)
    ],

    // ── J ────────────────────────────────────────────────────────────────────
    //  Rotation 0:  X . .    Rotation 1:  X X .    Rotation 2:  . . .    Rotation 3:  . X .
    //               X X X                X . .                  X X X                . X .
    //               . . .                X . .                  . . X                . X X
    TetrominoType.J: [
      [[0, 0], [1, 0], [1, 1], [1, 2]], // 0°
      [[0, 0], [0, 1], [1, 0], [2, 0]], // 90°
      [[1, 0], [1, 1], [1, 2], [2, 2]], // 180°
      [[0, 2], [1, 2], [2, 1], [2, 2]], // 270°
    ],

    // ── L ────────────────────────────────────────────────────────────────────
    //  Rotation 0:  . . X    Rotation 1:  X . .    Rotation 2:  . . .    Rotation 3:  . X X
    //               X X X                X . .                  X X X                . . X
    //               . . .                X X .                  X . .                . . X
    TetrominoType.L: [
      [[0, 2], [1, 0], [1, 1], [1, 2]], // 0°
      [[0, 0], [1, 0], [2, 0], [2, 1]], // 90°
      [[1, 0], [1, 1], [1, 2], [2, 0]], // 180°
      [[0, 1], [0, 2], [1, 2], [2, 2]], // 270°
    ],
  };
}
